def make_adt(out):
 sys.path.insert(0,str(ROOT/'sources/UniXNU/scripts'))
 from unixnu.devicetree import node,empty_nvram_proxy
 blob=(out/'qemu-virt.dtb').read_bytes();fdt=read_fdt(blob);nodes=list(fdt.walk())
 ram=next(n for n in nodes if n.strings('device_type')==['memory']);[(dram_base,dram_size)]=registers(ram)
 io=[n for n in nodes if any(c in ['arm,gic-v3','arm,pl011'] for c in n.strings('compatible'))]
 spans=[(a,n) for entry in io for a,n in registers(entry)];base=min(a for a,n in spans);end=max(a+n for a,n in spans)
 cpus=next(n for n in fdt.children if n.name=='cpus');cpu=next(n for n in cpus.children if n.strings('device_type')==['cpu'])
 affinity=cpu.cells('reg');assert affinity==[0]
 gic=next(n for n in nodes if 'arm,gic-v3' in n.strings('compatible'));gic_regs=registers(gic);assert len(gic_regs)==2
 timer=next(n for n in nodes if 'arm,armv8-timer' in n.strings('compatible'));ints=timer.cells('interrupts');assert len(ints)==12
 kind,irq,flags=ints[3:6];assert kind==1 and 0<=irq<16 and flags&15 in [4,8]
 properties=[('compatible',b'arm,gic-v3\0'),('reg',struct.pack('<4Q',*[v for a,n in gic_regs for v in [a-base,n]]))]
 if 'redistributor-stride' in gic.properties:
  stride=int.from_bytes(gic.properties['redistributor-stride'],'big');properties.append(('redistributor-stride',struct.pack('<Q',stride)))
 cpu_properties=[('unixnu,boot-cpu',struct.pack('<I',1)),('unixnu,timer-intid',struct.pack('<I',16+irq)),
  ('unixnu,physical-timer',struct.pack('<I',1)),('unixnu,timer-flags',struct.pack('<I',flags&15))]
 tree=node('device-tree',[('model',fdt.properties['model']),('compatible',fdt.properties['compatible'])],[
  node('chosen',[('dram-base',struct.pack('<Q',dram_base)),('dram-size',struct.pack('<Q',dram_size)),('random-seed',os.urandom(64)),*empty_nvram_proxy()],[node('memory-map',[])]),
  node('cpus',[],[node('cpu0',[('device_type',b'cpu\0'),('reg',struct.pack('<I',affinity[0])),('state',b'running\0'),
   ('compatible',cpu.properties['compatible']),('timebase-frequency',struct.pack('<I',62500000)),*cpu_properties])]),
  node('arm-io',[('device_type',b'arm-io\0'),('ranges',struct.pack('<3Q',0,base,end-base))],[node('intc',properties)]),node('defaults',[]),node('options',[])])
 path=out/'kernel.macho.adt';path.write_bytes(tree)
 return path,dict(dtb_sha256=sha(blob),adt_sha256=sha(tree),dram_base=dram_base,dram_bytes=dram_size,io_ranges=spans,timer_specifier=ints[3:6],timer_intid=16+irq,
  timebase_frequency=62500000,frequency_requires_same_run_mrs_confirmation=True,hardware_qualified=False)


def main():
 p=argparse.ArgumentParser();p.add_argument('--stop-at',choices=['arm_init','bsd_init','timer_irq','find_root'],default='arm_init');p.add_argument('--observe-seconds',type=int,default=55);a=p.parse_args()
 assert 5<=a.observe_seconds<=60
 parent=ROOT/'artifacts/native-sec-dxe-qemu';parent.mkdir(parents=True,exist_ok=True)
